import assert from "node:assert/strict";
import { join } from "node:path";
import { readFileSync, readdirSync, existsSync } from "node:fs";
import { spawnSync } from "node:child_process";

const config = JSON.parse(readFileSync("src-tauri/tauri.conf.json"));
assert.equal(
  config.bundle.macOS.signingIdentity,
  "-",
  "the supported macOS channel is ad-hoc signing without Apple account credentials",
);
assert.deepEqual(config.app.security.capabilities, ["main"]);
assert.notEqual(config.app.withGlobalTauri, true);
assert.equal(config.app.windows.length, 1, "one normal WebView window");
assert.equal(config.bundle.linux.deb.desktopTemplate, "marktub.desktop");
const desktop = readFileSync("src-tauri/marktub.desktop", "utf8");
assert(
  desktop.includes("Exec={{exec}} %F"),
  "desktop file-open arguments missing",
);
assert(desktop.includes("MimeType=text/markdown;"));
assert.deepEqual(config.bundle.fileAssociations, [
  {
    ext: ["md", "markdown"],
    name: "Markdown document",
    role: "Editor",
    rank: "Alternate",
    mimeType: "text/markdown",
  },
]);
assert(
  readFileSync("dist/index.html", "utf8").includes('type="module"'),
  "blank baseline frontend; rebuild normally",
);
const capability = JSON.parse(readFileSync("src-tauri/capabilities/main.json"));
assert(
  capability.permissions.every(
    (permission) =>
      !/wdio|e2e|test-fixture|core:window:allow-(?:set-focus|is-focused)/.test(
        permission,
      ),
  ),
  "test permission in main capability",
);
const chunks = readdirSync("dist/assets").filter((file) =>
  file.endsWith(".js"),
);
for (const chunk of chunks) {
  const source = readFileSync(`dist/assets/${chunk}`, "utf8");
  for (const marker of [
    "marktubPierreProbe",
    "wdioTauri",
    "__wdio_mocks__",
    "WDIO Plugin",
    "plugin:wdio|",
  ])
    assert(!source.includes(marker), `test evaluator in ${chunk}: ${marker}`);
}
assert(
  !existsSync("src-tauri/permissions/autogenerated/e2e_fixture.toml"),
  "stale autogenerated test command permission; rebuild normally",
);
const targetDirectory = process.env.CARGO_TARGET_DIR ?? "src-tauri/target";
const binaryPath = join(
  targetDirectory,
  process.platform === "darwin"
    ? "release/bundle/macos/Marktub.app/Contents/MacOS/marktub"
    : "release/marktub",
);
const binary = readFileSync(binaryPath);
assert(
  binary.includes(Buffer.from("take_os_open")),
  "normal app OS-open handler absent; reject blank baseline artifact",
);
for (const marker of [
  "e2e_fixture",
  "allow-e2e-fixture",
  "WDIO Plugin",
  "wdioTauri",
  "plugin:wdio|",
  "MARKTUB_TEST_",
])
  assert(
    !binary.includes(Buffer.from(marker)),
    `test command/server marker in normal executable: ${marker}`,
  );
const tree = spawnSync(
  "cargo",
  [
    "tree",
    "--manifest-path",
    "src-tauri/Cargo.toml",
    "--locked",
    "-e",
    "normal",
  ],
  { encoding: "utf8" },
);
assert.equal(tree.status, 0, tree.stderr);
assert(
  !tree.stdout.includes("tauri-plugin-wdio"),
  "test server appears in normal dependency graph",
);
console.log(
  "PASS: normal frontend has no WDIO evaluator; normal config, generated ACL, executable and Rust graph have no test fixture/server/evaluator markers.",
);
