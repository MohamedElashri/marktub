import { execFileSync } from "node:child_process";
import { lstatSync, readFileSync, realpathSync } from "node:fs";
import { homedir } from "node:os";
import { resolve, relative, isAbsolute } from "node:path";
import { fileURLToPath } from "node:url";

export function publicationFiles(root) {
  const deleted = new Set(
    execFileSync("git", ["ls-files", "--deleted", "-z"], {
      cwd: root,
      encoding: "utf8",
    })
      .split("\0")
      .filter(Boolean),
  );
  return [
    ...new Set(
      execFileSync(
        "git",
        ["ls-files", "--cached", "--others", "--exclude-standard", "-z"],
        {
          cwd: root,
          encoding: "utf8",
          maxBuffer: 16 * 1024 * 1024,
        },
      )
        .split("\0")
        .filter((file) => file && !deleted.has(file)),
    ),
  ].sort();
}

export function inspectPublication(root, files) {
  const issues = [];
  const generated =
    /^(?:artifacts|node_modules|\.pnpm-store|dist|\.git|\.agents|\.codex|\.aws)(?:\/|$)|^src-tauri\/(?:target|gen|permissions\/autogenerated)(?:\/|$)|^tests\/(?:generated|probes)(?:\/|$)|^docs(?:\/|$)|^src-tauri\/src\/probes(?:\.rs|\/)/;
  const credentials =
    /(?:^|\/)(?:\.env(?:\..*)?|id_(?:rsa|ed25519)|credentials|.*\.(?:p8|p12|pfx|pem|key))$/i;
  const secrets =
    /-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----|\bAKIA[0-9A-Z]{16}\b|\bgh[pousr]_[A-Za-z0-9]{35,}\b|\bnpm_[A-Za-z0-9]{36,}\b/;
  for (const file of files) {
    const absolute = resolve(root, file);
    const local = relative(root, absolute);
    if (
      !local ||
      local === ".." ||
      local.startsWith("../") ||
      isAbsolute(local)
    ) {
      issues.push("Inventory contains a path outside the source root.");
      continue;
    }
    if (
      generated.test(file) ||
      /(?:^|\/)(?:\.DS_Store|__pycache__)(?:\/|$)|\.(?:log|pyc|bak|orig|rej|swp)$|~$|(?:^|\/)[^/]+\.app(?:\/|$)|\.(?:dmg|tar\.gz)$/.test(
        file,
      )
    ) {
      issues.push(
        `${file}: generated, local or superseded development material.`,
      );
      continue;
    }
    if (credentials.test(file) && !file.endsWith(".env.example")) {
      issues.push(`${file}: credential/configuration file is not publishable.`);
      continue;
    }
    let stat;
    try {
      stat = lstatSync(absolute);
      if (relative(realpathSync(root), realpathSync(absolute)) !== local) {
        issues.push(`${file}: symlink traversal is not publishable.`);
        continue;
      }
    } catch {
      issues.push(`${file}: source entry is missing or unreadable.`);
      continue;
    }
    if (!stat.isFile() || stat.isSymbolicLink()) {
      issues.push(`${file}: source inventory must contain ordinary files.`);
      continue;
    }
    if (stat.size > 8 * 1024 * 1024) {
      issues.push(
        `${file}: oversized source entry; review for generated assets.`,
      );
      continue;
    }
    const bytes = readFileSync(absolute);
    if (!bytes.includes(0)) {
      const text = bytes.toString("utf8");
      if (secrets.test(text))
        issues.push(`${file}: possible private key/token; value withheld.`);
      if (text.includes(homedir() + "/"))
        issues.push(`${file}: local home path; redact before publication.`);
    }
  }
  return issues;
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  const root = process.cwd();
  execFileSync("python3", ["scripts/check-dependencies.py"], {
    cwd: root,
    stdio: "pipe",
  });
  const files = publicationFiles(root);
  const issues = inspectPublication(root, files);
  if (issues.length) {
    console.error(issues.join("\n"));
    process.exitCode = 1;
  } else if (process.argv.includes("--json")) {
    console.log(JSON.stringify(files));
  } else {
    console.log(
      `PASS: ${files.length} publication files; no generated output, local reports, credentials, detected tokens or local home paths.`,
    );
  }
}
