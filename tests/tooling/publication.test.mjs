import { test } from "node:test";
import assert from "node:assert/strict";
import {
  mkdtempSync,
  mkdirSync,
  writeFileSync,
  symlinkSync,
  rmSync,
  unlinkSync,
} from "node:fs";
import { tmpdir, homedir } from "node:os";
import { join } from "node:path";
import { execFileSync } from "node:child_process";
import {
  inspectPublication,
  publicationFiles,
} from "../../scripts/check-repository.mjs";

function fixture(action) {
  const root = mkdtempSync(join(tmpdir(), "marktub-publication-"));
  try {
    action(root);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
}
test("publication admits maintained source, tests and mandatory notices", () =>
  fixture((root) => {
    for (const file of ["app.ts", "NOTICE", "test.ts"])
      writeFileSync(join(root, file), "ordinary source");
    assert.deepEqual(
      inspectPublication(root, ["app.ts", "NOTICE", "test.ts"]),
      [],
    );
  }));
test("publication refuses generated or credential files even when explicitly listed", () =>
  fixture((root) => {
    const issues = inspectPublication(root, [
      "artifacts/report.json",
      "src-tauri/permissions/autogenerated/a.toml",
      "docs/local-notes.md",
      ".env",
      "certificate.p12",
    ]);
    assert.equal(issues.length, 5);
  }));
test("publication refuses secrets and local home paths without echoing values", () =>
  fixture((root) => {
    const secret = ["-----BEGIN", "PRIVATE KEY-----"].join(" ");
    writeFileSync(join(root, "secret.txt"), secret);
    writeFileSync(join(root, "local.txt"), homedir() + "/private-file");
    const issues = inspectPublication(root, ["secret.txt", "local.txt"]);
    assert.equal(issues.length, 2);
    assert(!issues.join("\n").includes(secret));
    assert(!issues.join("\n").includes(homedir()));
  }));
test("publication refuses outside paths and symlinks", () =>
  fixture((root) => {
    mkdirSync(join(root, "src"));
    writeFileSync(join(root, "outside.txt"), "fixture");
    symlinkSync("../outside.txt", join(root, "src/link.txt"));
    mkdirSync(join(root, "real"));
    writeFileSync(join(root, "real/inside.txt"), "fixture");
    symlinkSync("real", join(root, "alias"));
    assert.equal(
      inspectPublication(root, [
        "../outside.txt",
        "src/link.txt",
        "alias/inside.txt",
      ]).length,
      3,
    );
  }));

test("publication excludes intentionally deleted tracked files and includes new source", () =>
  fixture((root) => {
    execFileSync("git", ["init", "-q"], { cwd: root });
    writeFileSync(join(root, "old.ts"), "obsolete");
    execFileSync("git", ["add", "old.ts"], { cwd: root });
    unlinkSync(join(root, "old.ts"));
    writeFileSync(join(root, "new.ts"), "maintained");
    assert.deepEqual(publicationFiles(root), ["new.ts"]);
  }));
